"""BAG (Bathymetric Attributed Grid, ONS 1.6) writer through GDAL's BAG driver (single-resolution).

Band 1 elevation (up +, negative depths), band 2 uncertainty (95 %, m); no data 1 000 000. The ISO 19115 XML
metadata is generated by GDAL from the template variables given here (responsible party, abstract, vertical
datum, uncertainty type, processing step, date). BAG needs a projected CRS."""
from __future__ import annotations

import datetime as _dt

import numpy as np

NODATA = 1000000.0


def bag_available():
    try:
        import rasterio
        with rasterio.Env() as env:
            return "BAG" in env.drivers()
    except Exception:  # noqa: BLE001
        return False


def write_bag(path, elev, unc, transform, crs, vertical_datum_name="", individual="", organisation="",
              abstract="", process_step="", restriction="otherRestrictions", other_constraints="",
              classification="unclassified"):
    """elev, unc: (rows, cols) north-up arrays (NaN = no data); unc None → 1 000 000 (unknown).
    crs: rasterio CRS or anything pyproj accepts. Returns the path."""
    import rasterio
    from pyproj import CRS
    c = CRS.from_user_input(crs.to_wkt() if hasattr(crs, "to_wkt") else crs)
    if not c.is_projected:
        raise ValueError("BAG needs a projected coordinate system (e.g. TWD97 / TM2 or UTM)")
    rcrs = rasterio.crs.CRS.from_wkt(c.to_wkt())
    z = np.where(np.isfinite(elev), elev, NODATA).astype(np.float32)
    if unc is None:
        u = np.full(z.shape, NODATA, np.float32)
    else:
        u = np.where(np.isfinite(unc) & np.isfinite(elev), unc, NODATA).astype(np.float32)
    now = _dt.datetime.now(_dt.timezone.utc)
    vert_wkt = (f'VERT_CS["{vertical_datum_name}", VERT_DATUM["{vertical_datum_name}", 2000]]'
                if vertical_datum_name else "")
    opts = {"VAR_INDIVIDUAL_NAME": individual or "unknown", "VAR_ORGANISATION_NAME": organisation or "unknown",
            "VAR_POSITION_NAME": "", "VAR_DATE": now.strftime("%Y-%m-%d"),
            "VAR_ABSTRACT": abstract or "Bathymetric surface", "VAR_STATUS": "completed",
            "VAR_RESTRICTION_CODE": restriction, "VAR_OTHER_CONSTRAINTS": other_constraints or "none",
            "VAR_CLASSIFICATION": classification, "VAR_SECURITY_USER_NOTE": "none",
            "VAR_PROCESS_STEP_DESCRIPTION": process_step or "Generated by PointCloud Studio",
            "VAR_DATETIME": now.strftime("%Y-%m-%dT%H:%M:%S"), "VAR_VERTICAL_UNCERT_CODE": "productUncert",
            "VAR_RES_UNIT": "Metre"}
    if vert_wkt:
        opts["VAR_VERT_WKT"] = vert_wkt
    with rasterio.open(path, "w", driver="BAG", width=z.shape[1], height=z.shape[0], count=2, dtype="float32",
                       crs=rcrs, transform=transform, nodata=NODATA, **opts) as ds:
        ds.write(z, 1)
        ds.write(u, 2)
    return path
